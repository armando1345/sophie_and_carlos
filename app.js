function hashLike(value) {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(i);
    hash |= 0; // 32-bit signed
  }
  return (hash >>> 0).toString(16).slice(0, 16);
}


